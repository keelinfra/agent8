"""Unit tests for tools/sbom.py: python3 -m unittest discover -s test (test/unit.sh runs them)."""
import contextlib
import hashlib
import json
import os
import runpy
import subprocess
import sys
import tempfile
import unittest
import zipfile
from unittest import mock

SBOM = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tools", "sbom.py")


def write_jar(path, entries):
    with zipfile.ZipFile(path, "w") as z:
        for name, data in entries.items():
            z.writestr(name, data)
    return path


def sha256(path):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


class SbomTest(unittest.TestCase):

    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        d = self.tmp.name
        self.deps = os.path.join(d, "deps")
        os.mkdir(self.deps)
        for name in ("asm", "asm-commons", "asm-tree", "jvmdg"):
            with open(os.path.join(self.deps, name + ".jar"), "wb") as f:
                f.write(name.encode() * 10)
        # The controller's agent.jar: remoting's own pom.properties plus two libraries it bundles,
        # one of them listed twice (as with shaded copies).
        lib = "#Generated by Maven\ngroupId=org.jenkins-ci\nartifactId=constant-pool-scanner\nversion=1.2\n"
        self.agent = write_jar(os.path.join(d, "agent.jar"), {
            "META-INF/MANIFEST.MF": "Manifest-Version: 1.0\r\nVersion: 3309.v27b_9314fd1a_4\r\n",
            "META-INF/maven/org.jenkins-ci.main/remoting/pom.properties":
                "groupId=org.jenkins-ci.main\nartifactId=remoting\nversion=3309.v27b_9314fd1a_4\n",
            "META-INF/maven/org.jenkins-ci/constant-pool-scanner/pom.properties": lib,
            "META-INF/maven/shaded/constant-pool-scanner/pom.properties": lib,
            "META-INF/maven/commons-io/commons-io/pom.properties":
                "groupId=commons-io\nartifactId=commons-io\nversion=2.18.0\n",
            "META-INF/maven/commons-io/commons-io/pom.xml": "<project/>",
            "hudson/remoting/Launcher.class": b"\xca\xfe\xba\xbe",
        })

    def agent8_jar(self, name="agent8-java8.jar", jvmdg_version=None):
        manifest = ("Manifest-Version: 1.0\r\nMain-Class: io.keelinfra.agent8.Main\r\n"
                    "Agent8-Remoting-Version: 3309.v27b_9314fd1a_4\r\nAgent8-Target-Java: 8\r\n")
        if jvmdg_version:
            manifest += "JvmDowngrader-Version: %s\r\n" % jvmdg_version
        return write_jar(os.path.join(self.tmp.name, name), {"META-INF/MANIFEST.MF": manifest})

    def sbom(self, jar, env=None, git=None):
        """Runs tools/sbom.py on jar; git, if given, stands in for subprocess.run (the git call)."""
        out = os.path.join(self.tmp.name, "out.cdx.json")
        environ = {k: v for k, v in os.environ.items() if k != "AGENT8_VERSION"}
        environ.update(env or {})
        with contextlib.ExitStack() as stack:
            stack.enter_context(mock.patch.object(sys, "argv", [SBOM, jar, self.agent, self.deps, out]))
            stack.enter_context(mock.patch.dict(os.environ, environ, clear=True))
            if git is not None:
                stack.enter_context(mock.patch("subprocess.run", git))
            runpy.run_path(SBOM, run_name="__main__")
        with open(out) as f:
            text = f.read()
        self.assertTrue(text.endswith("}\n"))
        return json.loads(text)

    def test_document(self):
        bom = self.sbom(self.agent8_jar())
        self.assertEqual(bom["bomFormat"], "CycloneDX")
        self.assertEqual(bom["specVersion"], "1.6")
        self.assertEqual(bom["version"], 1)
        self.assertRegex(bom["serialNumber"], r"^urn:uuid:[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[0-9a-f]{4}-[0-9a-f]{12}$")
        self.assertRegex(bom["metadata"]["timestamp"], r"^\d{4}-\d\d-\d\dT\d\d:\d\d:\d\dZ$")
        self.assertNotEqual(self.sbom(self.agent8_jar())["serialNumber"], bom["serialNumber"])

    def test_agent8_component(self):
        jar = self.agent8_jar()
        main = self.sbom(jar)["metadata"]["component"]
        self.assertEqual(main["type"], "application")
        self.assertEqual(main["bom-ref"], "agent8")
        self.assertEqual(main["name"], "agent8-java8")
        self.assertEqual(main["version"], "3309.v27b_9314fd1a_4")
        self.assertEqual(main["description"], "Jenkins agent for hosts on Java 8 and newer")
        self.assertEqual(main["supplier"], {"name": "keelinfra", "url": ["https://keelinfra.io"]})
        self.assertEqual(main["licenses"], [{"license": {"id": "MIT"}}])
        self.assertEqual(main["hashes"], [{"alg": "SHA-256", "content": sha256(jar)}])
        self.assertEqual(main["externalReferences"], [{"type": "vcs", "url": "https://github.com/keelinfra/agent8"}])
        props = {p["name"]: p["value"] for p in main["properties"]}
        self.assertEqual(props["agent8:remoting-version"], "3309.v27b_9314fd1a_4")
        self.assertEqual(props["agent8:target-java"], "8")

    def test_release_version_from_environment(self):
        jar = self.agent8_jar()
        self.assertEqual(self.sbom(jar, {"AGENT8_VERSION": "jenkins-2.528.1"})["metadata"]["component"]["version"],
                         "jenkins-2.528.1")
        self.assertEqual(self.sbom(jar, {"AGENT8_VERSION": ""})["metadata"]["component"]["version"],
                         "3309.v27b_9314fd1a_4")

    def test_name_without_jar_suffix(self):
        jar = self.agent8_jar(name="agent8-build")
        self.assertEqual(self.sbom(jar)["metadata"]["component"]["name"], "agent8-build")

    def test_components(self):
        bom = self.sbom(self.agent8_jar())
        c = {x["bom-ref"]: x for x in bom["components"]}
        self.assertEqual(list(c), [
            "pkg:maven/org.jenkins-ci.main/remoting@3309.v27b_9314fd1a_4",
            "pkg:maven/commons-io/commons-io@2.18.0",
            "pkg:maven/org.jenkins-ci/constant-pool-scanner@1.2",
            "pkg:maven/org.ow2.asm/asm@9.8",
            "pkg:maven/org.ow2.asm/asm-commons@9.8",
            "pkg:maven/org.ow2.asm/asm-tree@9.8",
            "pkg:maven/xyz.wagyourtail.jvmdowngrader/jvmdowngrader@2.0.1?classifier=all",
        ])
        remoting = c["pkg:maven/org.jenkins-ci.main/remoting@3309.v27b_9314fd1a_4"]
        self.assertEqual(remoting, {
            "type": "library",
            "bom-ref": "pkg:maven/org.jenkins-ci.main/remoting@3309.v27b_9314fd1a_4",
            "group": "org.jenkins-ci.main",
            "name": "remoting",
            "version": "3309.v27b_9314fd1a_4",
            "description": "Jenkins agent (remoting), downgraded to Java 8 bytecode",
            "purl": "pkg:maven/org.jenkins-ci.main/remoting@3309.v27b_9314fd1a_4",
            "licenses": [{"license": {"id": "MIT"}}],
            "hashes": [{"alg": "SHA-256", "content": sha256(self.agent)}],
        })
        bundled = c["pkg:maven/org.jenkins-ci/constant-pool-scanner@1.2"]
        self.assertEqual(bundled["description"], "Bundled inside Jenkins remoting")
        self.assertNotIn("hashes", bundled)
        self.assertNotIn("licenses", bundled)
        for a in ("asm", "asm-commons", "asm-tree"):
            asm = c["pkg:maven/org.ow2.asm/%s@9.8" % a]
            self.assertEqual(asm["licenses"], [{"license": {"id": "BSD-3-Clause"}}])
            self.assertEqual(asm["hashes"], [{"alg": "SHA-256", "content": sha256(os.path.join(self.deps, a + ".jar"))}])
        jvmdg = c["pkg:maven/xyz.wagyourtail.jvmdowngrader/jvmdowngrader@2.0.1?classifier=all"]
        self.assertEqual(jvmdg["version"], "2.0.1")
        self.assertEqual(jvmdg["purl"], "pkg:maven/xyz.wagyourtail.jvmdowngrader/jvmdowngrader@2.0.1?classifier=all")
        self.assertEqual(jvmdg["licenses"], [{"license": {"name": "LGPL-2.1"}}])
        self.assertEqual(jvmdg["hashes"], [{"alg": "SHA-256", "content": sha256(os.path.join(self.deps, "jvmdg.jar"))}])

    def test_jvmdg_version_from_manifest(self):
        bom = self.sbom(self.agent8_jar(jvmdg_version="2.1.0"))
        refs = [x["bom-ref"] for x in bom["components"]]
        self.assertIn("pkg:maven/xyz.wagyourtail.jvmdowngrader/jvmdowngrader@2.1.0?classifier=all", refs)

    def test_dependencies(self):
        bom = self.sbom(self.agent8_jar())
        refs = [x["bom-ref"] for x in bom["components"]]
        self.assertEqual(len(refs), len(set(refs)))
        self.assertEqual(bom["dependencies"], [{"ref": "agent8", "dependsOn": refs}] + [{"ref": r} for r in refs])

    def test_commit(self):
        head = subprocess.run(["git", "rev-parse", "HEAD"], capture_output=True, text=True,
                              cwd=os.path.dirname(SBOM)).stdout.strip()
        props = {p["name"]: p["value"] for p in self.sbom(self.agent8_jar())["metadata"]["component"]["properties"]}
        if head:
            self.assertRegex(head, r"^[0-9a-f]{40,64}$")
            self.assertEqual(props["agent8:commit"], head)
        else:  # not run from a Git checkout
            self.assertNotIn("agent8:commit", props)

    def test_no_commit_outside_git(self):
        calls = []

        def not_a_repository(cmd, **kwargs):
            calls.append((cmd, kwargs["cwd"]))
            return subprocess.CompletedProcess(cmd, 128, stdout="", stderr="fatal: not a git repository")

        main = self.sbom(self.agent8_jar(), git=not_a_repository)["metadata"]["component"]
        self.assertEqual(calls, [(["git", "rev-parse", "HEAD"], os.path.dirname(os.path.abspath(SBOM)))])
        self.assertNotIn("agent8:commit", [p["name"] for p in main["properties"]])

    def test_no_commit_without_git(self):
        main = self.sbom(self.agent8_jar(), git=mock.Mock(side_effect=FileNotFoundError("git")))["metadata"]["component"]
        self.assertEqual([p["name"] for p in main["properties"]], ["agent8:remoting-version", "agent8:target-java"])

    def test_not_an_agent8_jar(self):
        with self.assertRaises(KeyError):
            self.sbom(write_jar(os.path.join(self.tmp.name, "other.jar"), {"META-INF/MANIFEST.MF": "Version: 1\r\n"}))
        self.assertFalse(os.path.exists(os.path.join(self.tmp.name, "out.cdx.json")))


if __name__ == "__main__":
    unittest.main()
